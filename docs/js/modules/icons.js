/**
 * Monta o caminho do SVG local de uma tecnologia cadastrada no `data.js`.
 * Para adicionar uma tecnologia, basta salvar `<slug>.svg` em
 * `assets/images/technologies/` e usar o mesmo slug no `data.js`.
 *
 * @param {string} slug - Slug da tecnologia (ex.: "javascript", "react").
 * @returns {string} Imagem SVG pronta para ser inserida no markup.
 */
export function buildTechnologyIcon(slug) {
    const safeSlug = String(slug || "")
        .toLowerCase()
        .replace(/[^a-z0-9-]/g, "");
    const letter = safeSlug.charAt(0).toUpperCase() || "?";
    const source = `assets/images/technologies/${safeSlug}.svg`;

    return `<img src="${source}" alt="" class="skill-item-icon" loading="lazy" onerror="this.replaceWith(makeFallback('${letter}'))">`;
}

/**
 * Cria um elemento `<span>` usado como substituto (fallback) para
 * tecnologias sem ícone cadastrado.
 *
 * É exposta em `window.makeFallback` para que possa ser referenciada
 * diretamente em handlers `onerror` inline no HTML gerado.
 *
 * @param {string} letter - Letra a ser exibida no fallback.
 * @returns {HTMLSpanElement} Elemento pronto para inserir no DOM.
 */
export function makeFallback(letter) {
    const span = document.createElement("span");
    span.className = "skill-item-icon-fallback";
    span.setAttribute("aria-hidden", "true");
    span.textContent = letter || "?";
    return span;
}

// Mantém a função acessível no escopo global, pois é chamada a partir
// de atributos `onerror="..."` inlines gerados dinamicamente.
if (typeof window !== "undefined") {
    window.makeFallback = makeFallback;
}
